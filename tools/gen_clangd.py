from __future__ import annotations

from pathlib import Path

LIBRARY_INCLUDES = ("libservicelocator/include", "libCerfEngine/include", "libCerfCore/include",
                    "libCerfFrontend/include")

FIXED_FLAGS = ('"--target=i686-pc-windows-msvc"', '"/std:c++20"', '"/EHsc"', '"/permissive-"',
               '"-DWIN32"', '"-D_CONSOLE"', '"-DNDEBUG"', '"-DUNICODE"', '"-D_UNICODE"',
               '"-DCERF_DEV_MODE=1"')


def generate(root: Path) -> Path:
    vcpkg_include = root / "vcpkg_installed" / "x86-windows-static" / "x86-windows-static" / "include"
    if not vcpkg_include.is_dir():
        print("[clangd] note: vcpkg include dir not present yet ({}).".format(vcpkg_include))
        print("[clangd]       It appears after the first msbuild restore; .clangd still written.")
    lines = [
        "# AUTO-GENERATED by tools/gen_clangd.py -- do not edit; regenerated on every build.",
        "# Makes clangd parse CERF with the same flags as the msbuild (cerf.vcxproj) build.",
        "CompileFlags:",
        "  Compiler: clang-cl",
        "  Add:",
    ]
    lines += ["    - " + flag for flag in FIXED_FLAGS]
    lines.append('    - "-I{}"'.format(vcpkg_include.as_posix()))
    lines += ['    - "-I{}"'.format((root / inc).as_posix()) for inc in LIBRARY_INCLUDES]
    dest = root / ".clangd"
    dest.write_bytes("\n".join(lines).encode("utf-8"))
    print("[clangd] wrote {} (vcpkg include: {})".format(dest, vcpkg_include))
    return dest


if __name__ == "__main__":
    generate(Path(__file__).resolve().parent.parent)

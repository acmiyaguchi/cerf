inline constexpr uint32_t kXKeycodeEvdevOffset = 8;

struct EvdevSidedVk {
    uint32_t evdev;
    uint8_t  vk;
};

/* Linux input-event-codes.h KEY_LEFTCTRL 29, KEY_RIGHTCTRL 97, KEY_LEFTSHIFT 42,
   KEY_RIGHTSHIFT 54, KEY_LEFTALT 56, KEY_RIGHTALT 100; Windows SDK WinUser.h VK_LSHIFT
   0xA0 .. VK_RMENU 0xA5. */
inline constexpr EvdevSidedVk kEvdevSidedVks[] = {
    {29, 0xA2}, {97, 0xA3}, {42, 0xA0}, {54, 0xA1}, {56, 0xA4}, {100, 0xA5},
};

inline constexpr uint8_t SidedVk(uint32_t evdev, uint8_t vk) {
    for (const EvdevSidedVk& s : kEvdevSidedVks)
        if (s.evdev == evdev) return s.vk;
    return vk;
}
